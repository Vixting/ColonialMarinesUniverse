using Content.Client._RMC14.UserInterface;
using Content.Client.CMU14.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using static Content.Client.CMU14.Chemistry.Research.ResearchDataTerminalWindow;

namespace Content.Client.CMU14.Chemistry.Research;

[GenerateTypedNameReferences]
public sealed partial class ResearchDocumentRow : BoxContainer
{
    public int Id;
    public Action<int>? OnRead;
    public Action<int>? OnPrint;

    public ResearchDocumentRow()
    {
        RobustXamlLoader.Load(this);

        foreach (var button in new[] { ReadButton, PrintButton })
        {
            button.Modulate = Color.White;
            button.ModulateSelfOverride = Color.White;
            button.StyleBoxOverride = new StyleBoxFlat
            {
                BackgroundColor = AmberBright,
                BorderColor = AmberBorder,
                BorderThickness = new Thickness(2),
            };
        }

        IconButton(ReadButton, CMUIcons.Book, Loc.GetString("research-data-ui-read"));
        IconButton(PrintButton, CMUIcons.Print, Loc.GetString("research-data-ui-print"));

        ReadButton.OnPressed += _ => OnRead?.Invoke(Id);
        PrintButton.OnPressed += _ => OnPrint?.Invoke(Id);
    }

    private static void IconButton(Button button, string texturePath, string text)
    {
        var row = button.AddIconLabel(texturePath, text, 16, HAlignment.Center, AmberBlack);
        row.SeparationOverride = 4;
        row.Margin = new Thickness(4, 2);
    }
}
