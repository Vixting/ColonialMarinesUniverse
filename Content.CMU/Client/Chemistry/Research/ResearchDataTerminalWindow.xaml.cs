using System.Collections.Generic;
using Content.Client._RMC14.UserInterface;
using Content.Client.CMU14.UI;
using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.CMU14.Chemistry.Research;

[GenerateTypedNameReferences]
public sealed partial class ResearchDataTerminalWindow : DefaultWindow
{
    public static readonly Color AmberBright = Color.FromHex("#FAC000");
    public static readonly Color AmberDim = Color.FromHex("#C69214");
    public static readonly Color AmberBlack = Color.FromHex("#221801");
    public static readonly Color AmberBorder = Color.FromHex("#8A6800");
    public static readonly Color AmberWashed = Color.FromHex("#7A6A2E");

    [Dependency] private IGameTiming _timing = default!;

    public TimeSpan CycleStart;
    public TimeSpan CycleEnd;

    public readonly Label ReduceCooldownLabel;
    public readonly Label ReprintContractLabel;
    public readonly Label UpgradeLabel;

    private readonly List<ResearchTabButton> _tabButtons = new();
    private readonly Dictionary<Button, RMCIconLabelRow> _sortRows = new();

    public ResearchDataTerminalWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        RemoveWindowBorder(this);

        var resourceCache = IoCManager.Resolve<IResourceCache>();
        var smallFont = resourceCache.GetFont("/Fonts/NotoSans/NotoSans-Regular.ttf", 8);

        ReduceCooldownLabel = Icon(ReduceCooldownButton, CMUIcons.Play, Loc.GetString("research-data-ui-reduce-cooldown"));
        ReprintContractLabel = Icon(ReprintContractButton, CMUIcons.ArrowsRotate, Loc.GetString("research-data-ui-reprint"));
        UpgradeLabel = Icon(UpgradeButton, CMUIcons.Gear, string.Empty);

        HideOldReportsButton.Label.FontColorOverride = AmberBright;
        ContractCooldownLabel.FontOverride = smallFont;

        foreach (var button in new[] { DocumentsSortTimeButton, DocumentsSortCompoundButton })
        {
            var row = button.AddIconLabel(CMUIcons.ArrowDown19, button.Text ?? string.Empty, 14, fontColor: AmberBright);
            row.Icon.IdleColor = AmberBright;
            row.Icon.Texture = null;
            _sortRows[button] = row;
        }

        BuildTabBar();
    }

    public void SetSortIcon(Button button, string? icon)
    {
        var row = _sortRows[button];
        if (icon == null)
            row.Icon.Texture = null;
        else
            row.SetIcon(icon);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (CycleEnd <= CycleStart)
        {
            ContractCooldownBar.Value = 0;
            ContractCooldownLabel.Text = string.Empty;
            return;
        }

        var time = _timing.CurTime;
        var remaining = CycleEnd - time;
        if (remaining < TimeSpan.Zero)
            remaining = TimeSpan.Zero;

        ContractCooldownBar.MinValue = (float) CycleStart.TotalSeconds;
        ContractCooldownBar.MaxValue = (float) CycleEnd.TotalSeconds;
        ContractCooldownBar.Value = (float) time.TotalSeconds;
        ContractCooldownLabel.Text = Loc.GetString("research-data-ui-time-left", ("TIME", (int) remaining.TotalSeconds));
    }

    private void BuildTabBar()
    {
        _tabButtons.Clear();
        TabBar.RemoveAllChildren();

        AddTabButton(CMUIcons.Gear, Loc.GetString("research-data-ui-manage-line1"), Loc.GetString("research-data-ui-manage-line2"));
        AddTabButton(CMUIcons.Flask, Loc.GetString("research-data-ui-view-line1"), Loc.GetString("research-data-ui-view-line2"));

        SetActiveTab(Tabs.CurrentTab);
        Tabs.OnTabChanged += SetActiveTab;
    }

    private void AddTabButton(string iconPath, string line1, string line2)
    {
        var index = _tabButtons.Count;
        var tab = new ResearchTabButton();
        tab.Setup(iconPath, line1, line2);
        tab.OnPressed += _ => Tabs.CurrentTab = index;
        TabBar.AddChild(tab);
        _tabButtons.Add(tab);
    }

    private void SetActiveTab(int index)
    {
        for (var i = 0; i < _tabButtons.Count; i++)
        {
            _tabButtons[i].SetActive(i == index);
        }
    }

    public static void SetPurchasableStyle(Button button, bool enabled, Color? disabledColor = null, Label? label = null)
    {
        if (button.StyleBoxOverride is StyleBoxFlat box)
            box.BackgroundColor = enabled ? AmberBright : disabledColor ?? Color.Transparent;

        if (label != null)
            label.FontColorOverride = enabled ? AmberBlack : AmberBright;
    }

    public static void RemoveWindowBorder(DefaultWindow window)
    {
        window.Contents.Margin = new Thickness(0);
        if (window.GetChild(0) is PanelContainer panel)
            panel.PanelOverride = new StyleBoxFlat { BackgroundColor = AmberBlack };
    }

    private static Label Icon(Button button, string texturePath, string text)
    {
        var row = button.AddIconLabel(texturePath, text, 16, HAlignment.Stretch, AmberBlack);
        row.Margin = new Thickness(10, 0, 6, 0);
        row.SeparationOverride = 8;
        return row.Label;
    }
}
