using Content.Client._RMC14.UserInterface;
using Content.Client.CMU14.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using static Content.Client.CMU14.Chemistry.Research.ResearchDataTerminalWindow;

namespace Content.Client.CMU14.Chemistry.Research;

[GenerateTypedNameReferences]
public sealed partial class ResearchConfirmWindow : DefaultWindow
{
    private readonly RMCIconLabelRow _acceptRow;
    private readonly RMCIconLabelRow _denyRow;

    public ResearchConfirmWindow()
    {
        RobustXamlLoader.Load(this);
        RemoveWindowBorder(this);

        _acceptRow = AcceptButton.AddIconLabel(CMUIcons.Check, string.Empty, 16, HAlignment.Center, AmberBlack);
        _denyRow = DenyButton.AddIconLabel(CMUIcons.Ban, string.Empty, 16, HAlignment.Center, AmberBright);
        _denyRow.Icon.IdleColor = AmberBright;
    }

    public void Setup(string title, string text, string accept, string deny)
    {
        Title = title;
        MessageLabel.SetMessage(text, defaultColor: AmberBright);
        _acceptRow.Label.Text = accept;
        _denyRow.Label.Text = deny;
    }
}
